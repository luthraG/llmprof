/* Prebuild step for the hosted dashboard demo at /llmprof/try/.
 *
 * The demo IS the real dashboard. Rather than fork app.js/app.css/index.html
 * into the docs tree (where they would rot), we copy them from the single
 * source of truth (src/llmprof/ui/) into public/try/ at build time and apply the
 * few transforms demo mode needs:
 *   - point the asset links at the sibling copies under /try/,
 *   - stamp window.__LLMPROF_VER with the snapshot's ver so app.js does not
 *     decide the tab is stale and reload-loop,
 *   - load demo.js (the fetch shim + banner) before app.js.
 *
 * demo.js and demo-data.json are committed; demo-data.json is regenerated by
 * scripts/demo/gen_demo_data.py when the data model changes. This script is pure
 * Node so the Astro/GitHub Pages build stays Node-only.
 */
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const uiDir = join(here, "..", "..", "src", "llmprof", "ui");
const outDir = join(here, "..", "public", "try");
const dataFile = join(outDir, "demo-data.json");

if (!existsSync(dataFile)) {
  console.error(
    "build-try: missing public/try/demo-data.json.\n" +
    "Generate it first: python scripts/demo/gen_demo_data.py"
  );
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });

const ver = JSON.parse(readFileSync(dataFile, "utf8")).ver;
if (!ver) {
  console.error("build-try: demo-data.json has no `ver` field.");
  process.exit(1);
}

// app.js and app.css ship verbatim alongside the demo files.
copyFileSync(join(uiDir, "app.js"), join(outDir, "app.js"));
copyFileSync(join(uiDir, "app.css"), join(outDir, "app.css"));

let html = readFileSync(join(uiDir, "index.html"), "utf8");
// Social-card metadata for the most-shared launch link. The dashboard shell has
// none (it is an app, not a page); the demo is what people paste into chats and
// timelines, so it gets a proper preview card. Reuses the live docs og.png.
const ogMeta = [
  '<title>llmprof - live demo</title>',
  '<meta property="og:title" content="llmprof - live demo">',
  '<meta property="og:description" content="Try the llmprof dashboard in your browser. A flame graph of where every token and dollar goes in an LLM call, on a recorded session. No install.">',
  '<meta property="og:image" content="https://luthrag.github.io/llmprof/og.png">',
  '<meta property="og:image:width" content="1200">',
  '<meta property="og:image:height" content="630">',
  '<meta property="og:url" content="https://luthrag.github.io/llmprof/try/">',
  '<meta property="og:type" content="website">',
  '<meta name="twitter:card" content="summary_large_image">',
  '<meta name="twitter:title" content="llmprof - live demo">',
  '<meta name="twitter:description" content="The llmprof dashboard in your browser, on a recorded session. See where every token and dollar goes. No install.">',
  '<meta name="twitter:image" content="https://luthrag.github.io/llmprof/og.png">',
].join("\n");

html = html
  .replaceAll("/llmprof/app.css", "./app.css")
  .replaceAll("/llmprof/app.js", "./app.js")
  .replace("__ASSET_VER__", ver)
  .replace("<title>llmprof</title>", ogMeta)
  // load the shim before the app so the fetch interceptor is in place first
  .replace('<script src="./app.js"></script>', '<script src="./demo.js"></script>\n<script src="./app.js"></script>');

writeFileSync(join(outDir, "index.html"), html, "utf8");

console.log(`build-try: wrote public/try/{index.html,app.js,app.css} (ver ${ver})`);
